import type { TKey } from "./i18n";

/**
 * 首页配色墙的配色方案库。
 *
 * 全部手工设计，按 10 个标签各 12 组铺开。**每个标签下先定一条用色规则再逐组设计** ——
 * 否则 120 组摆在一起会「一看就是按色系排的」（`color-duos.ts` 的注释里记过这个坑）。
 *
 * ## 设计规则（照 coolors 真实方案的思路）
 *
 * 1. **每组 3–10 色，数量不固定** —— 数量整齐划一本身就是「一眼假」的来源。
 *    上限 10 是给参考站那批「完整色阶」留的（见末尾「精选」段的说明）。
 * 2. **颜色来自多个色相**，不是同一色相的深→浅阶梯。常见结构：
 *    主色 + 辅色 + 中性底 + 对比点缀（如深红 + 奶油 + 深蓝）；类似色 + 一个对比色；
 *    互补 / 三角。纯灰阶方案（极简那几个）是唯一例外，但必须靠明度把方案撑起来。
 * 3. 组内明度有层次、饱和度有变化，不要全是高饱和或全是灰。
 * 4. 颜色要和 `name` 的意象对得上（「深海航线」得是蓝系为主）。
 *
 * 各标签的侧重：
 *
 * - 自然：绿为主，混土壤棕 / 天空蓝 / 花点缀
 * - 日落：暖色梯度为主，但**必须有一个冷色锚**（暮蓝 / 暮紫 / 天青）—— 纯暖色的
 *   色相跨度只有 40° 上下，过不了校验，而且看多了也腻
 * - 柔和：高明度，但色相要跨开（粉 + 蓝 + 薄荷 + 奶油），不是一片淡粉
 * - 复古：70 年代印刷感，芥末 / 锈橙 / 橄榄 / 砖红 + 奶油白，再配一个青或蓝压住
 * - 霓虹：近黑底 + 2–3 个高饱和霓虹，组内明暗对比拉到最大
 * - 大地：土壤 / 黏土 / 沙 / 岩，棕褐色系低饱和，配青绿或蓝做对比
 * - 海洋：蓝青为主，深浅海分层，可带泡沫白、珊瑚橙或极光紫
 * - 极简：白与近白为主，中性灰阶 + 一个深色锚点，最多一个克制的彩色点缀。
 *   多数组是「纯灰阶 + 单点缀」，走校验里的中性色分支
 * - 都市：混凝土灰 + 一个醒目信号色，或灰阶 + 一点城市天空蓝
 * - 夜行：深蓝紫灰为主 + 柔光；**刻意与霓虹区分** —— 霓虹是纯黑底 + 高饱和，
 *   夜行是深色 + 低饱和柔光
 *
 * 校验靠 `node scripts/check-palettes.mjs`：id 唯一、hex 合法、**组内色相跨度 ≥60°**
 * （挡同色系明暗阶梯）、组内有明度跨度、跨组无近似重复、每个 name 都出现在
 * `en.palettes.ts` 里。改数据后**一定要跑一遍**，跨组近似重复是肉眼看不出来的。
 *
 * `name` 是中文名，同时是 i18n 词典 key（见 `src/lib/i18n/en.palettes.ts`）。
 */
export type PaletteTag =
  | "nature"
  | "sunset"
  | "pastel"
  | "retro"
  | "neon"
  | "earth"
  | "ocean"
  | "minimal"
  | "urban"
  | "night";

export type CuratedPalette = {
  /** 稳定 slug：React key、以及「这组方案是否已收藏」的比对依据。 */
  id: string;
  /**
   * 中文名，同时是 i18n 词典 key。
   *
   * 类型写成 `TKey` 而不是 `string` 是有意的：`TKey = keyof typeof en`，写错一个字
   * 编译期就报错，调用点可以直接 `t(p.name)` 而不用断言。代价是新增方案时
   * 必须先把名字加进 `en.palettes.ts`。
   */
  name: TKey;
  /** 3–10 个大写 hex。数量刻意不固定，见文件头的设计规则。 */
  colors: readonly string[];
  tags: readonly PaletteTag[];
  /**
   * 取自参考站的精选段（见文件末尾）。
   *
   * **只影响展示顺序** —— `PaletteWall` 用它把精选和手工那批在桶内混开。
   * 不做这件事的话，精选全排在数组末尾、每个标签桶的前 12 位都是手工方案，
   * 首屏一张精选都看不到，要滚到第 30 行才露头，等于没穿插。
   */
  featured?: boolean;
};

/**
 * 「这组配色是否已收藏」的比对 key。
 *
 * 必须与 store 的 `normalizeSavedColors`（只做大写化、**保序**）对齐 ——
 * 顺序或大小写对不上，收藏过的那颗心形就不会亮。
 */
export function paletteKey(colors: readonly string[]) {
  return colors.map((c) => c.toUpperCase()).join(",");
}

